  constructor(private cdr: ChangeDetectorRef, private elementRef: ElementRef) {}

  @HostListener('document:click', ['$event'])
  onDocumentClick(event: MouseEvent) {
    if (!this.elementRef.nativeElement.contains(event.target)) {
      this.showEmojiPicker = false;
      this.cdr.markForCheck();
    }
  }

  toggleEmojiPicker() {
    this.showEmojiPicker = !this.showEmojiPicker;
    this.cdr.markForCheck();
  }

  selectIcon(emoji: string) {
    this.emojiSelected.emit(emoji);
    this.cdr.markForCheck();
  }

  getEmojiCategories(): string[] {
    return Object.keys(this.emojiCategories);
  }

  getCategoryIcon(category: string): string {
    return this.emojiCategories[category]?.[0] || '😊';
  }

  selectEmojiCategory(category: string) {
    this.selectedEmojiCategory = category;
    setTimeout(() => {
      const element = document.getElementById(`emoji-category-${category}`);
      const container = element?.closest('.overflow-y-auto');
      if (element && container) {
        (container as HTMLElement).scrollTop = element.offsetTop - 10;
      }
    }, 0);
    this.cdr.markForCheck();
  }

  onEmojiGridScroll(event: any) {
    const scrollContainer = event.target;
    const categories = this.getEmojiCategories();
    
    for (const category of categories) {
      const element = document.getElementById(`emoji-category-${category}`);
      if (element) {
        const rect = element.getBoundingClientRect();
        const containerRect = scrollContainer.getBoundingClientRect();
        
        if (rect.top <= containerRect.top + 50) {
          this.selectedEmojiCategory = category;
          this.cdr.markForCheck();
        }
      }
    }
  }
